<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Cuándo sale tu pedido</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Los pedidos confirmados antes de las 14:00 de un día laborable salen ese mismo día. Los posteriores, y los de fin de semana o festivo, salen el siguiente día laborable.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>En cuanto el paquete sale de nuestras instalaciones recibes un correo con el número de seguimiento para consultarlo con el transportista.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Pedidos con grabado personalizado</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>El grabado se realiza en nuestro taller y añade <strong>2–3 días laborables</strong> al plazo habitual. Si necesitas el pedido para una fecha concreta, indícalo en las observaciones o escríbenos antes de comprar: en la mayoría de casos podemos ajustarnos.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Pedidos de volumen y regalo de empresa</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Los lotes para empresa se coordinan caso por caso: fijamos contigo la fecha de entrega al hacer el presupuesto. Para pedidos grandes con grabado, cuenta con un margen de una semana.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Canarias, Ceuta y Melilla</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Estos destinos están fuera del territorio aduanero del IVA peninsular, por lo que el envío requiere despacho de aduana. Los impuestos y tasas de importación que aplique el destino corren por cuenta del destinatario y son ajenos a nuestra tarifa. El plazo de entrega también puede ampliarse por el trámite aduanero.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Qué hacer si el paquete llega dañado</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Revisa el embalaje antes de firmar. Si ves golpes, roturas o el paquete abierto, <strong>indícalo en el albarán del transportista</strong> al firmar y avísanos en 24 horas con un par de fotos. Con esa anotación podemos reclamar al transportista y reponerte la pieza sin coste.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Sin esa anotación en el albarán la reclamación es mucho más difícil, así que merece la pena el minuto que cuesta.</p>
<!-- /wp:paragraph -->

