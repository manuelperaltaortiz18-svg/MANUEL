<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">En qué estado debe volver</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>El producto debe llegar completo, sin uso más allá de lo necesario para comprobarlo, y con su embalaje original. Puedes examinar la pieza como lo harías en una tienda; lo que no procede es haberla usado.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Un cuchillo que ya ha cortado, o un soporte con marcas de uso, han perdido valor y podemos descontar esa depreciación del reembolso.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Productos con grabado personalizado</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Las piezas grabadas a medida están <strong>excluidas del derecho de desistimiento</strong>, porque se fabrican según tus especificaciones y no podemos revenderlas. Por eso te avisamos de ello en la propia ficha del producto antes de comprar.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Esta exclusión no afecta a la garantía: si una pieza grabada llega con un defecto de fábrica, la cubrimos igual que cualquier otra.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Defecto de fábrica y garantía</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Si el producto presenta un defecto de fabricación, <strong>el coste de la devolución es nuestro</strong>. Organizamos la recogida y te reparamos o sustituimos la pieza sin que tengas que adelantar nada.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Todos nuestros productos cuentan con la <strong>garantía legal de tres años</strong> frente a faltas de conformidad, con el respaldo de Cuperinox. Escríbenos con tu número de pedido y unas fotos del defecto y lo resolvemos.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>La garantía no cubre el desgaste normal por uso, el óxido derivado de un mantenimiento incorrecto (como lavar los cuchillos en lavavajillas), los golpes, ni las modificaciones hechas por terceros. En la página de <a href="/cuidado/">cuidado y mantenimiento</a> te contamos cómo evitarlo.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Cuándo recibes el dinero</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Te devolvemos el importe por el mismo medio de pago que usaste, en un plazo máximo de <strong>14 días naturales</strong> desde que ejerces el desistimiento. Podemos esperar a haber recibido el producto, o a que nos acredites que lo has enviado, antes de emitir el reembolso.</p>
<!-- /wp:paragraph -->

