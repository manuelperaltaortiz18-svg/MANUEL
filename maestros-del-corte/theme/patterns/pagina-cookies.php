<h2 class="wp-block-heading">Qué son las cookies</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Una cookie es un pequeño archivo que se descarga en tu dispositivo al visitar una página web. Permite recordar información sobre tu visita, como el contenido de tu carrito o tus preferencias, y en algunos casos analizar tu navegación o mostrarte publicidad.</p>
