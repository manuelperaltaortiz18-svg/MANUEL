<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Cómo gestionar tus preferencias</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Al entrar por primera vez te mostramos un banner donde puedes <strong>aceptar todas, rechazar todas o configurarlas por categoría</strong>. Rechazar es tan sencillo como aceptar, y ninguna cookie no necesaria se instala hasta que decides.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Puedes cambiar de opinión cuando quieras desde el enlace de configuración de cookies disponible en el pie de página. Tu decisión se conserva 365 días; pasado ese plazo volveremos a preguntarte.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>También puedes bloquear o eliminar cookies desde la configuración de tu navegador. Ten en cuenta que si bloqueas las técnicas, es posible que la tienda no funcione correctamente y no puedas completar una compra.</p>
