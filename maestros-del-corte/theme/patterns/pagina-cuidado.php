<p class="has-contrast-soft-color has-text-color" style="font-size:1.125rem">Un buen cuchillo jamonero dura décadas. Lo que lo mata no es el uso: es el lavavajillas, la humedad y el cajón.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Los cuchillos</h2>
<!-- /wp:heading -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Nunca en el lavavajillas</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Es la regla que más filos arruina. Los detergentes de lavavajillas son abrasivos y alcalinos, y combinados con el calor y la humedad prolongada pican incluso el acero inoxidable. Además, el cuchillo golpea contra otras piezas y mella el filo.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Lávalo a mano con agua templada y jabón neutro, justo después de usarlo, y <strong>sécalo de inmediato</strong>. El acero inoxidable resiste la corrosión, pero no es inmune: lo que la provoca es dejarlo húmedo.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Guárdalo sin que roce</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Un cuchillo suelto en un cajón pierde filo cada vez que abres. Guárdalo en su estuche, en una barra magnética o en un taco. Si va a estar mucho tiempo sin usarse, una capa finísima de aceite mineral de uso alimentario en la hoja lo protege.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Chaira sí, afilado de vez en cuando</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>La chaira no afila: <strong>realinea</strong> el filo, que con el uso se va doblando microscópicamente. Pásala unas pocas veces antes de cada sesión de corte, con ángulo constante y sin fuerza.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Afilar de verdad —quitar material con piedra— hace falta pocas veces al año en uso doméstico. Cuando el cuchillo ya no muerde aunque pases la chaira, es el momento.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">La hoja alveolada</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Los alvéolos crean bolsas de aire que reducen la fricción y evitan que la loncha se pegue a la hoja. No afectan al afilado: se afila el filo, no los alvéolos. Límpialos bien, porque la grasa se acumula ahí.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">El soporte jamonero</h2>
<!-- /wp:heading -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">La base de madera</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Nunca la sumerjas ni la metas en el lavavajillas: la madera se hincha, se agrieta y pierde el acabado. Límpiala con un paño húmedo bien escurrido y sécala.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Un par de veces al año, pásale aceite mineral de uso alimentario con un paño, deja que absorba unos minutos y retira el sobrante. La madera recupera el tono y repele mejor la humedad.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3} -->
<h3 class="wp-block-heading">Los herrajes y el sistema giratorio</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Revisa de vez en cuando que los tornillos siguen apretados: con el uso y los cambios de humedad se aflojan, y un soporte que baila es un riesgo real con el cuchillo en la mano.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Mantén limpio el mecanismo giratorio, sin restos de grasa acumulada, para que siga girando suave y bloqueando firme.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">Las piezas grabadas</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>El grabado sobre acero es permanente y no requiere cuidado especial. Solo evita los limpiadores abrasivos y los estropajos metálicos sobre la zona grabada: no borran el grabado, pero sí pueden rayar el pulido de alrededor.</p>
<!-- /wp:paragraph -->

