<h3 class="wp-block-heading">Excepción: productos personalizados</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>De acuerdo con el artículo 103.c) del Real Decreto Legislativo 1/2007, <strong>no procede el derecho de desistimiento en los productos confeccionados conforme a las especificaciones del consumidor o claramente personalizados</strong>. Quedan por tanto excluidas las piezas con grabado personalizado, circunstancia que se advierte de forma expresa en la ficha de producto antes de la compra.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Esta exclusión no afecta en modo alguno a la garantía legal por falta de conformidad.</p>
