<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">8. Garantía legal</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Los productos cuentan con la garantía legal de conformidad de <strong>tres años</strong> desde la entrega, conforme al Real Decreto Legislativo 1/2007. Durante los dos primeros años se presume que las faltas de conformidad manifestadas ya existían en el momento de la entrega, salvo prueba en contrario.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>En caso de falta de conformidad, el cliente tiene derecho a la reparación o sustitución del producto, y subsidiariamente a la reducción del precio o la resolución del contrato. <strong>Los gastos de devolución derivados de una falta de conformidad son a cargo del vendedor</strong>, que organizará la recogida.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>La garantía no cubre el desgaste normal derivado del uso, los daños por golpes o caídas, la corrosión resultante de un mantenimiento inadecuado —en particular el lavado en lavavajillas o el almacenamiento en húmedo—, ni las manipulaciones o reparaciones realizadas por terceros.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":2} -->
<h2 class="wp-block-heading">9. Grabado personalizado</h2>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>El servicio de grabado se realiza <strong>únicamente sobre hoja de acero</strong>; los componentes de madera no admiten grabado. El texto se graba exactamente tal y como el cliente lo introduce en el pedido, por lo que <strong>la corrección ortográfica del texto es responsabilidad del cliente</strong>. No se admiten cambios una vez iniciada la producción.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>El vendedor se reserva el derecho de rechazar textos o signos de contenido ilícito, ofensivo, o que infrinjan derechos de propiedad industrial o intelectual de terceros. En el caso de grabados de logotipos o marcas, el cliente garantiza disponer de los derechos necesarios para su reproducción y responde frente a reclamaciones de terceros por este motivo.</p>
